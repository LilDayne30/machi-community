CREATE TABLE user_region_connections (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  region_id TEXT NOT NULL REFERENCES regions(id),
  status TEXT NOT NULL CHECK(status IN ('current','former','stay')),
  purpose TEXT NOT NULL DEFAULT '' CHECK(purpose IN ('','work','study')),
  start_year INTEGER CHECK(start_year BETWEEN 1900 AND 2100),
  end_year INTEGER CHECK(end_year BETWEEN 1900 AND 2100),
  updated_at INTEGER NOT NULL DEFAULT (unixepoch()),
  PRIMARY KEY(user_id,region_id,status),
  CHECK(end_year IS NULL OR start_year IS NULL OR end_year>=start_year),
  CHECK(status!='current' OR end_year IS NULL)
) STRICT;
CREATE UNIQUE INDEX one_current_residence ON user_region_connections(user_id) WHERE status='current';
CREATE INDEX region_residents ON user_region_connections(region_id,status);
